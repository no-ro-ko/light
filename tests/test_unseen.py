def measure(stories):
    o = Organism()
    for p in sorted(CUR.glob("*.txt")):
        o.read(p.name, p.read_text(encoding="utf-8"))
    o.sleep()
    for name, st in stories.items():
        o.read(name + ".txt", st["text"])
    o.sleep()
    L = o.lang

    def norm(w):
        return L.lemma(w.lower().replace("ё", "е")) if w else None

    ev = sp = q = 0
    for name, st in stories.items():
        items = [(i, s) for i, (src, s) in enumerate(o.memory) if src == name + ".txt"]
        got = {(e.agent, e.action, e.obj) for e in o._paraphrase(o.narr.events(o, items))}
        ev += sum(1 for g in st["gold"] if (norm(g[0]), norm(g[1]), norm(g[2])) in got)
        sp += sum(1 for g in st["speech"] if (norm(g[0]), norm(g[1]), norm(g[2])) in got)
        if st["question"]:
            question, want = st["question"]
            a = o.answer(question)
            q += want in a and f"«{name}.txt»" in a            # ответ — из этого рассказа
    return ev, sum(len(s["gold"]) for s in stories.values()), sp, \
        sum(len(s["speech"]) for s in stories.values()), q, sum(1 for s in stories.values() if s["question"])


class Unseen(unittest.TestCase):
    def test_set_1_after_fixes(self):
        ev, n, sp, ns, q, nq = measure(SET_1)
        print(f"\n  набор 1 (по нему исправляли): события {ev}/{n}, речь {sp}/{ns}, вопросы {q}/{nq}")
        self.assertGreaterEqual(ev, 34)

    def test_set_2_blind(self):
        ev, n, sp, ns, q, nq = measure(SET_2)
        print(f"\n  набор 2 (слепой): события {ev}/{n}, речь {sp}/{ns}, вопросы {q}/{nq}")
        self.assertGreaterEqual(ev, 19)


